"""Export basic-pitch's ICASSP 2022 saved model into a C++ source file.

Everything the C++ engine needs is pulled straight out of the official TensorFlow
SavedModel shipped with the `basic-pitch` package: conv kernels/biases, batch-norm
statistics, and the CQT constants (complex kernel, low-pass filter, bin lengths) that
were frozen into the graph when Spotify exported it. Values are written as hex-float
literals so the C++ side sees bit-identical float32 numbers.

Usage: python tools/export_model.py src/model_data.cpp
"""
import os
import sys

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "3")

import numpy as np
import tensorflow as tf
from basic_pitch import ICASSP_2022_MODEL_PATH


def hexf(arr):
    arr = np.asarray(arr, dtype=np.float32).ravel()
    return ",".join(float(x).hex() + "f" for x in arr)


def main(out_path):
    m = tf.saved_model.load(str(ICASSP_2022_MODEL_PATH))
    f = m.signatures["serving_default"]
    var = {v.name[:-2]: v.numpy() for v in m.variables}

    captured = [t.numpy() for t in f.captured_inputs if t.dtype == tf.float32]
    shapes = [c.shape for c in captured]
    assert shapes == [(36, 1, 256), (36, 1, 256), (256,)], shapes
    cqt_real, cqt_imag, lowpass = captured[0][:, 0, :], captured[1][:, 0, :], captured[2]
    # Which of the two kernels is real: nnaudio's real part is even-symmetric around the centre.
    fn = f.graph.as_graph_def().library.function[0]
    lengths = None
    for n in fn.node_def:
        if n.name.endswith("cq_t2010v2_1/Cast/x"):
            lengths = tf.make_ndarray(n.attr["value"].tensor).ravel()
    assert lengths is not None and lengths.shape == (309,)
    # order of captured inputs follows the order of use in the graph: real kernel first (conv1d), imag second
    sqrt_len = np.sqrt(lengths.astype(np.float32))  # tf.math.sqrt(tf.cast(lengths, float32))

    def bn(name):
        return dict(
            gamma=var[f"{name}/gamma"], beta=var[f"{name}/beta"],
            mean=var[f"{name}/moving_mean"], var=var[f"{name}/moving_variance"],
        )

    lines = [
        "// Generated by tools/export_model.py from basic-pitch's ICASSP 2022 SavedModel. Do not edit.",
        '#include "model_data.h"',
        "",
        "namespace bpp::data {",
        "",
    ]

    def arr(name, values, comment=""):
        values = np.asarray(values, dtype=np.float32)
        if comment:
            lines.append(f"// {comment}")
        lines.append(f"const float {name}[{values.size}] = {{{hexf(values)}}};")

    arr("kCqtKernelReal", cqt_real, "CQT top-octave kernel, real part, [36][256]")
    arr("kCqtKernelImag", cqt_imag, "CQT top-octave kernel, imaginary part, [36][256]")
    arr("kLowpass", lowpass, "anti-aliasing low-pass FIR for octave downsampling, [256]")
    arr("kCqtSqrtLengths", sqrt_len, "sqrt(float32(filter length)) per CQT bin, [309]")

    # Batch norm runs in oneDNN inside the SavedModel (parameters are variables, so Grappler cannot
    # fold them). Two kernels are used and their rounding differs:
    #   1 channel  (nspc_bnorm):     y = (x - mean) * (gamma / sqrt(var + eps)) + beta
    #   8/32 ch.   (bnorm_tbb_jit):  y = fma((x - mean) * (1 / sqrt(var + eps)), gamma, beta)
    # Verify both against TensorFlow before exporting.
    rng = np.random.default_rng(0)
    for prefix, name, ch in (("kBnCqt", "batch_normalization", 1), ("kBnContour", "batch_normalization_2", 8),
                             ("kBnOnset", "batch_normalization_3", 32)):
        p = bn(name)
        tv = {k: tf.Variable(v) for k, v in p.items()}
        bn_op = tf.function(lambda v, tv=tv: tf.raw_ops.FusedBatchNormV3(
            x=v, scale=tv["gamma"], offset=tv["beta"], mean=tv["mean"], variance=tv["var"], epsilon=0.001,
            is_training=False)[0])
        x = rng.normal(0.5, 1.0, (1, 64, 96, ch)).astype(np.float32)
        ref = bn_op(x).numpy()
        sd = np.sqrt(p["var"] + np.float32(0.001)).astype(np.float32)
        xm = (x - p["mean"]).astype(np.float32)
        if ch == 1:
            got = (xm * (p["gamma"] / sd).astype(np.float32)).astype(np.float32) + p["beta"]
        else:
            t = (xm * (np.float32(1) / sd).astype(np.float32)).astype(np.float32)
            got = (t.astype(np.float64) * p["gamma"] + p["beta"]).astype(np.float32)  # exact fma for these magnitudes
        assert np.array_equal(got, ref), f"batch norm formula mismatch for {name}: {np.mean(got == ref)}"
        for k in ("gamma", "beta", "mean", "var"):
            arr(f"{prefix}_{k}", p[k])

    for cname, key in (("kConvContour1", "conv2d_1"), ("kConvContour2", "contours-reduced"),
                       ("kConvNote1", "conv2d_2"), ("kConvNote2", "conv2d_3"),
                       ("kConvOnset1", "conv2d_4"), ("kConvOnset2", "conv2d_5")):
        k, b = var[f"{key}/kernel"], var[f"{key}/bias"]
        arr(f"{cname}_w", k, f"{key} kernel, HWIO {list(k.shape)}")
        arr(f"{cname}_b", b)

    lines += ["", "}  // namespace bpp::data", ""]
    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(lines))

    print("exported", out_path, {k: v.shape for k, v in var.items() if "kernel" in k})


if __name__ == "__main__":
    main(sys.argv[1])
